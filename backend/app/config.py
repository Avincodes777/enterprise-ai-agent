"""Centralized configuration and environment settings for Enterprise AI Agent."""

from functools import lru_cache
from typing import Optional, Set
from pydantic import AliasChoices, Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

SUPPORTED_EMBEDDING_PROVIDERS: Set[str] = {"fastembed", "openai"}
SUPPORTED_LLM_PROVIDERS: Set[str] = {"mock", "openai"}


class Settings(BaseSettings):
    """Application settings loaded from environment variables and .env file."""

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
    )

    # Core Environment
    app_env: str = Field(
        default="development",
        validation_alias="APP_ENV",
        description="Application runtime environment (development, staging, production, test)",
    )

    # Ingestion & Upload Configuration
    max_upload_size_bytes: int = Field(
        default=25 * 1024 * 1024,
        gt=0,
        validation_alias=AliasChoices("MAX_UPLOAD_SIZE_BYTES", "MAX_PDF_SIZE_BYTES"),
        description="Maximum allowed PDF upload size in bytes (default 25 MiB: 26214400 bytes)",
    )

    # Embedding Configuration
    embedding_provider: str = Field(
        default="fastembed",
        validation_alias="EMBEDDING_PROVIDER",
        description="Active embedding provider ('fastembed' or 'openai')",
    )
    embedding_model: str = Field(
        default="BAAI/bge-small-en-v1.5",
        validation_alias="EMBEDDING_MODEL",
        description="Embedding model name or identifier",
    )
    embedding_dimension: int = Field(
        default=384,
        gt=0,
        validation_alias="EMBEDDING_DIMENSION",
        description="Dimensionality of vectors generated by the embedding model",
    )
    embedding_batch_size: int = Field(
        default=64,
        gt=0,
        validation_alias="EMBEDDING_BATCH_SIZE",
        description="Maximum chunk batch size sent for embedding generation",
    )
    embedding_timeout_seconds: float = Field(
        default=30.0,
        gt=0.0,
        validation_alias="EMBEDDING_TIMEOUT_SECONDS",
        description="Timeout in seconds for embedding generation requests",
    )

    # LLM Configuration
    llm_provider: str = Field(
        default="mock",
        validation_alias="LLM_PROVIDER",
        description="Active LLM provider ('mock' or 'openai')",
    )
    llm_model: str = Field(
        default="gpt-4o-mini",
        validation_alias="LLM_MODEL",
        description="LLM model identifier",
    )
    llm_temperature: float = Field(
        default=0.0,
        ge=0.0,
        le=2.0,
        validation_alias="LLM_TEMPERATURE",
        description="Default generation temperature (0.0 to 2.0)",
    )
    llm_max_tokens: Optional[int] = Field(
        default=None,
        gt=0,
        validation_alias="LLM_MAX_TOKENS",
        description="Optional default maximum generation tokens",
    )

    # Optional Provider Credentials
    openai_api_key: Optional[str] = Field(
        default=None,
        validation_alias="OPENAI_API_KEY",
        description="API key for OpenAI services (optional for local fastembed execution)",
    )

    # Infrastructure Placeholders
    database_url: Optional[str] = Field(
        default=None,
        validation_alias="DATABASE_URL",
        description="Relational database connection string",
    )
    qdrant_url: Optional[str] = Field(
        default=None,
        validation_alias="QDRANT_URL",
        description="Qdrant vector database URL",
    )
    qdrant_collection_name: str = Field(
        default="enterprise_knowledge",
        validation_alias="QDRANT_COLLECTION_NAME",
        description="Name of the Qdrant collection for vector storage",
    )
    qdrant_api_key: Optional[str] = Field(
        default=None,
        validation_alias="QDRANT_API_KEY",
        description="Optional API key for Qdrant vector database",
    )
    qdrant_timeout_seconds: float = Field(
        default=10.0,
        gt=0.0,
        validation_alias="QDRANT_TIMEOUT_SECONDS",
        description="Timeout in seconds for Qdrant client operations",
    )
    redis_url: Optional[str] = Field(
        default=None,
        validation_alias="REDIS_URL",
        description="Redis cache connection string",
    )
    sqlite_db_path: str = Field(
        default="data/document_registry.db",
        validation_alias=AliasChoices("SQLITE_DB_PATH", "DOCUMENT_REGISTRY_DB_PATH"),
        description="Path to SQLite database file for persistent document registry",
    )

    @field_validator("sqlite_db_path")
    @classmethod
    def validate_sqlite_db_path(cls, value: str) -> str:
        """Validate that sqlite_db_path is a non-empty string."""
        if not isinstance(value, str) or not value.strip():
            raise ValueError("SQLITE_DB_PATH cannot be empty or whitespace-only")
        return value.strip()

    @field_validator("max_upload_size_bytes")
    @classmethod
    def validate_max_upload_size_bytes(cls, value: int) -> int:
        """Validate that max_upload_size_bytes is a strictly positive integer."""
        if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
            raise ValueError("MAX_UPLOAD_SIZE_BYTES must be a positive integer")
        return value

    @field_validator("embedding_provider", mode="before")
    @classmethod
    def validate_embedding_provider(cls, value: str) -> str:
        """Validate and normalize the embedding provider name."""
        if not isinstance(value, str):
            raise ValueError(f"EMBEDDING_PROVIDER must be a string, got {type(value).__name__}")

        normalized = value.strip().lower()
        if normalized not in SUPPORTED_EMBEDDING_PROVIDERS:
            supported = ", ".join(f"'{p}'" for p in sorted(SUPPORTED_EMBEDDING_PROVIDERS))
            raise ValueError(
                f"Unsupported embedding provider: '{value}'. Supported providers are: {supported}"
            )
        return normalized

    @field_validator("embedding_model")
    @classmethod
    def validate_embedding_model(cls, value: str) -> str:
        """Validate that the embedding model identifier is not empty."""
        if not isinstance(value, str) or not value.strip():
            raise ValueError("EMBEDDING_MODEL cannot be empty or whitespace-only")
        return value.strip()

    @field_validator("llm_provider", mode="before")
    @classmethod
    def validate_llm_provider(cls, value: str) -> str:
        """Validate and normalize the LLM provider name."""
        if not isinstance(value, str):
            raise ValueError(f"LLM_PROVIDER must be a string, got {type(value).__name__}")

        normalized = value.strip().lower()
        if normalized not in SUPPORTED_LLM_PROVIDERS:
            supported = ", ".join(f"'{p}'" for p in sorted(SUPPORTED_LLM_PROVIDERS))
            raise ValueError(
                f"Unsupported LLM provider: '{value}'. Supported providers are: {supported}"
            )
        return normalized

    @field_validator("llm_model")
    @classmethod
    def validate_llm_model(cls, value: str) -> str:
        """Validate that the LLM model identifier is not empty."""
        if not isinstance(value, str) or not value.strip():
            raise ValueError("LLM_MODEL cannot be empty or whitespace-only")
        return value.strip()

    @field_validator("llm_temperature")
    @classmethod
    def validate_llm_temperature(cls, value: float) -> float:
        """Validate that the generation temperature is numeric and within [0.0, 2.0]."""
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ValueError("LLM_TEMPERATURE must be a numeric value")
        if value < 0.0 or value > 2.0:
            raise ValueError("LLM_TEMPERATURE must be between 0.0 and 2.0")
        return float(value)

    @field_validator("llm_max_tokens")
    @classmethod
    def validate_llm_max_tokens(cls, value: Optional[int]) -> Optional[int]:
        """Validate that LLM_MAX_TOKENS is None or a strictly positive integer."""
        if value is None:
            return None
        if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
            raise ValueError("LLM_MAX_TOKENS must be a positive integer")
        return value

    @field_validator("qdrant_collection_name")
    @classmethod
    def validate_qdrant_collection_name(cls, value: str) -> str:
        """Validate that the Qdrant collection name is not empty or whitespace-only."""
        if not isinstance(value, str) or not value.strip():
            raise ValueError("QDRANT_COLLECTION_NAME cannot be empty or whitespace-only")
        return value.strip()


@lru_cache()
def get_settings() -> Settings:
    """Return a cached singleton instance of application Settings."""
    return Settings()


def reset_settings_cache() -> None:
    """Clear the cached shared Settings instance."""
    get_settings.cache_clear()
